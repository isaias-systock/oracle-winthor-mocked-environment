-- Seed isolada para cadastro de produtos.
-- Mantém a massa de 100 produtos e centraliza as tabelas:
-- PCPRODUT, PCEMBALAGEM, PCPRODFILIAL e PCPRODSIMIL.

BEGIN
  FOR i IN 1..100 LOOP
    MERGE INTO WINTHOR.PCPRODUT t
    USING (
      SELECT
        5000 + i AS CODPROD,
        'PRODUTO AVANCADO ' || LPAD(i, 3, '0') AS DESCRICAO,
        200 + MOD(i - 1, 25) + 1 AS CODEPTO,
        300 + MOD(i - 1, 25) + 1 AS CODSEC,
        ROUND(0.350 + (i * 0.071), 3) AS PESOBRUTO,
        ROUND(0.300 + (i * 0.066), 3) AS PESOLIQ,
        CASE MOD(i, 6)
          WHEN 0 THEN 24
          WHEN 1 THEN 1
          WHEN 2 THEN 6
          WHEN 3 THEN 12
          WHEN 4 THEN 18
          ELSE 20
        END AS QTUNITCX,
        CASE MOD(i, 4)
          WHEN 0 THEN 'CX'
          WHEN 1 THEN 'UN'
          WHEN 2 THEN 'PC'
          ELSE 'FD'
        END AS EMBALAGEM,
        ROUND(4.5 + (i * 0.83), 4) AS CUSTOREP
      FROM dual
    ) s
    ON (t.CODPROD = s.CODPROD)
    WHEN MATCHED THEN
      UPDATE SET
        t.DESCRICAO = s.DESCRICAO,
        t.CODEPTO = s.CODEPTO,
        t.CODSEC = s.CODSEC,
        t.PESOBRUTO = s.PESOBRUTO,
        t.PESOLIQ = s.PESOLIQ,
        t.QTUNITCX = s.QTUNITCX,
        t.EMBALAGEM = s.EMBALAGEM,
        t.CUSTOREP = s.CUSTOREP
    WHEN NOT MATCHED THEN
      INSERT (
        CODPROD, DESCRICAO, CODEPTO, CODSEC, PESOBRUTO, PESOLIQ, QTUNITCX, EMBALAGEM, CUSTOREP
      )
      VALUES (
        s.CODPROD, s.DESCRICAO, s.CODEPTO, s.CODSEC, s.PESOBRUTO, s.PESOLIQ, s.QTUNITCX, s.EMBALAGEM, s.CUSTOREP
      );
  END LOOP;
END;
