BEGIN
  FOR filial_rec IN (
    SELECT DISTINCT TRIM(CODIGO) AS CODFILIAL
    FROM WINTHOR.PCFILIAL
    WHERE CODIGO IS NOT NULL
  ) LOOP
    FOR i IN 1..100 LOOP
      MERGE INTO WINTHOR.PCEMBALAGEM t
      USING (
        SELECT
          TO_NUMBER(filial_rec.CODFILIAL) * 1000000000000 + 5000 + i AS CODAUXILIAR,
          5000 + i AS CODPROD,
          CASE MOD(i, 4)
            WHEN 0 THEN 'CX'
            WHEN 1 THEN 'UN'
            WHEN 2 THEN 'PC'
            ELSE 'FD'
          END AS EMBALAGEM,
          'UN' AS UNIDADE,
          1 AS QTUNIT,
          ROUND(8.5 + (i * 0.95), 3) AS PTABELA,
          ROUND(7.9 + (i * 0.91), 3) AS PVENDA,
          DATE '2026-04-20' - MOD(i, 10) AS DTULTALTPTABELA,
          DATE '2026-04-20' - MOD(i, 8) AS DTULTALTPVENDA,
          100 + MOD(i - 1, 25) + 1 AS CODFUNCALTPTABELA,
          100 + MOD(i - 1, 25) + 1 AS CODFUNCALTPVENDA,
          100 + MOD(i, 50) AS QTMAXVENDA,
          ROUND(12 + MOD(i, 18), 2) AS MARGEM,
          30 + MOD(i, 120) AS PRAZOVAL,
          filial_rec.CODFILIAL AS CODFILIAL,
          'N' AS EXCLUIDO,
          'S' AS PERMITEMULTIPLICACAO,
          'S' AS USABALANCATOLEDO,
          ROUND(0.350 + (i * 0.071), 8) AS PESOBRUTO,
          ROUND(0.300 + (i * 0.066), 8) AS PESOLIQ,
          CASE MOD(i, 4)
            WHEN 0 THEN 24
            WHEN 1 THEN 1
            WHEN 2 THEN 6
            ELSE 12
          END AS QTMULTIPLA,
          ROUND(1.00000000, 8) AS FATORCONVERSAO,
          DATE '2026-04-20' - MOD(i, 15) AS DTCADASTRO
        FROM dual
      ) s
      ON (t.CODAUXILIAR = s.CODAUXILIAR AND t.CODPROD = s.CODPROD)
      WHEN MATCHED THEN
        UPDATE SET
          t.EMBALAGEM = s.EMBALAGEM,
          t.UNIDADE = s.UNIDADE,
          t.QTUNIT = s.QTUNIT,
          t.PTABELA = s.PTABELA,
          t.PVENDA = s.PVENDA,
          t.DTULTALTPTABELA = s.DTULTALTPTABELA,
          t.DTULTALTPVENDA = s.DTULTALTPVENDA,
          t.CODFUNCALTPTABELA = s.CODFUNCALTPTABELA,
          t.CODFUNCALTPVENDA = s.CODFUNCALTPVENDA,
          t.QTMAXVENDA = s.QTMAXVENDA,
          t.MARGEM = s.MARGEM,
          t.PRAZOVAL = s.PRAZOVAL,
          t.CODFILIAL = s.CODFILIAL,
          t.EXCLUIDO = s.EXCLUIDO,
          t.PERMITEMULTIPLICACAO = s.PERMITEMULTIPLICACAO,
          t.USABALANCATOLEDO = s.USABALANCATOLEDO,
          t.PESOBRUTO = s.PESOBRUTO,
          t.PESOLIQ = s.PESOLIQ,
          t.QTMULTIPLA = s.QTMULTIPLA,
          t.FATORCONVERSAO = s.FATORCONVERSAO,
          t.DTCADASTRO = s.DTCADASTRO
      WHEN NOT MATCHED THEN
        INSERT (
          CODAUXILIAR, CODPROD, EMBALAGEM, UNIDADE, QTUNIT, PTABELA, PVENDA,
          DTULTALTPTABELA, DTULTALTPVENDA, CODFUNCALTPTABELA, CODFUNCALTPVENDA,
          QTMAXVENDA, MARGEM, PRAZOVAL, CODFILIAL, EXCLUIDO, PERMITEMULTIPLICACAO,
          USABALANCATOLEDO, PESOBRUTO, PESOLIQ, QTMULTIPLA, FATORCONVERSAO, DTCADASTRO
        )
        VALUES (
          s.CODAUXILIAR, s.CODPROD, s.EMBALAGEM, s.UNIDADE, s.QTUNIT, s.PTABELA, s.PVENDA,
          s.DTULTALTPTABELA, s.DTULTALTPVENDA, s.CODFUNCALTPTABELA, s.CODFUNCALTPVENDA,
          s.QTMAXVENDA, s.MARGEM, s.PRAZOVAL, s.CODFILIAL, s.EXCLUIDO, s.PERMITEMULTIPLICACAO,
          s.USABALANCATOLEDO, s.PESOBRUTO, s.PESOLIQ, s.QTMULTIPLA, s.FATORCONVERSAO, s.DTCADASTRO
        );
    END LOOP;
  END LOOP;
END;
