BEGIN
  FOR i IN 1..15 LOOP
    MERGE INTO WINTHOR.PCPRODSIMIL t
    USING (
      SELECT
        5000 + i AS CODPROD,
        5000 + i + 1 AS CODSIMIL,
        100 + MOD(i - 1, 25) + 1 AS CODFUNCLANC,
        DATE '2026-04-20' - MOD(i, 12) AS DTLANC,
        CASE MOD(i, 2)
          WHEN 0 THEN 'V'
          ELSE 'A'
        END AS TIPOPROD,
        MOD(i - 1, 9) + 1 AS PRIORIDADE,
        CASE MOD(i, 3)
          WHEN 0 THEN 'T'
          WHEN 1 THEN 'S'
          ELSE 'A'
        END AS TIPOTROCA,
        'Produto similar isolado em seed propria' AS OBSERVACAO
      FROM dual
    ) s
    ON (t.CODPROD = s.CODPROD AND t.CODSIMIL = s.CODSIMIL)
    WHEN MATCHED THEN
      UPDATE SET
        t.CODFUNCLANC = s.CODFUNCLANC,
        t.DTLANC = s.DTLANC,
        t.TIPOPROD = s.TIPOPROD,
        t.PRIORIDADE = s.PRIORIDADE,
        t.TIPOTROCA = s.TIPOTROCA,
        t.OBSERVACAO = s.OBSERVACAO
    WHEN NOT MATCHED THEN
      INSERT (CODPROD, CODSIMIL, CODFUNCLANC, DTLANC, TIPOPROD, PRIORIDADE, TIPOTROCA, OBSERVACAO)
      VALUES (s.CODPROD, s.CODSIMIL, s.CODFUNCLANC, s.DTLANC, s.TIPOPROD, s.PRIORIDADE, s.TIPOTROCA, s.OBSERVACAO);
  END LOOP;
END;
