BEGIN
  FOR filial_rec IN (
    SELECT DISTINCT TRIM(CODIGO) AS CODFILIAL
    FROM WINTHOR.PCFILIAL
    WHERE CODIGO IS NOT NULL
  ) LOOP
    FOR i IN 1..100 LOOP
      MERGE INTO WINTHOR.PCPRODFILIAL t
      USING (
        SELECT
          5000 + i AS CODPROD,
          filial_rec.CODFILIAL AS CODFILIAL,
          100 + MOD(i - 1, 25) + 1 AS CODCOMPRADOR,
          'N' AS PROIBIDAVENDA,
          'N' AS FORALINHA,
          'S' AS REVENDA,
          20 + MOD(i, 30) AS ESTOQUEIDEAL,
          CASE MOD(i, 4)
            WHEN 0 THEN 24
            WHEN 1 THEN 1
            WHEN 2 THEN 6
            ELSE 12
          END AS MULTIPLO,
          'S' AS ATIVO,
          5 + MOD(i, 20) AS ESTOQUEMIN,
          120 + MOD(i * 3, 80) AS ESTOQUEMAX
