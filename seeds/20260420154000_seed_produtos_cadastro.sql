BEGIN
  FOR i IN 1..100 LOOP
    MERGE INTO WINTHOR.PCTABPR t
    USING (
      SELECT
        5000 + i AS CODPROD,
        1 AS NUMREGIAO,
        ROUND(10.5 + MOD(i, 35) + (i * 0.11), 6) AS PTABELA,
        ROUND(9.9 + MOD(i, 33) + (i * 0.10), 6) AS PVENDA,
        ROUND(3 + MOD(i, 8), 2) AS PERDESCMAX,
        ROUND(12 + MOD(i, 16), 2) AS MARGEM,
        'N' AS EXCLUIDO,
        DATE '2026-04-20' - MOD(i, 15) AS DTULTALTPVENDA
      FROM dual
    ) s
    ON (t.CODPROD = s.CODPROD AND t.NUMREGIAO = s.NUMREGIAO)
    WHEN MATCHED THEN
      UPDATE SET
        t.PTABELA = s.PTABELA,
        t.PVENDA = s.PVENDA,
        t.PERDESCMAX = s.PERDESCMAX,
        t.MARGEM = s.MARGEM,
        t.EXCLUIDO = s.EXCLUIDO,
        t.DTULTALTPVENDA = s.DTULTALTPVENDA
    WHEN NOT MATCHED THEN
      INSERT (CODPROD, NUMREGIAO, PTABELA, PVENDA, PERDESCMAX, MARGEM, EXCLUIDO, DTULTALTPVENDA)
